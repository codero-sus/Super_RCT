#!/usr/bin/env python3
"""Generate the command tables used by both bot variants.

Reads src/commands.def (Linux) and src/commands_windows.def (Windows) and writes:
  src/commands_table.h   (C: RCT_COMMANDS picks the Windows table on _WIN32)
  src/commands_table.py  (Python: COMMANDS picks the Windows table on win32)

Usage:
  python3 tools/gen_commands.py          # regenerate
  python3 tools/gen_commands.py --check  # exit 1 if the outputs are stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEF = os.path.join(ROOT, "src", "commands.def")
DEF_WIN = os.path.join(ROOT, "src", "commands_windows.def")
OUT_H = os.path.join(ROOT, "src", "commands_table.h")
OUT_PY = os.path.join(ROOT, "src", "commands_table.py")

NAME_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
WIN_PATH_RE = re.compile(r"^[A-Za-z]:\\")
BUILTINS = {
    "help", "commands", "auth", "logout", "status", "ip",
    "health", "diagnose", "mem", "swap", "disk", "load", "temp", "cpu", "net_rate", "procs",
    "uptime_h", "failed_units", "updates_count", "reboot_required", "alert",
    "report", "remind", "timers", "timer_cancel", "watch", "watch_check",
    "notify", "echo", "botstats", "sessions", "logout_all", "about", "selftest",
    "config", "run",
}
KINDS = {"f", "c", "b"}


def parse(path, windows=False):
    entries = []
    seen = set()
    with open(path, encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = line.split("|")
            if len(parts) != 4:
                sys.exit(f"{path}:{lineno}: expected 4 '|'-separated fields")
            name, kind, target, desc = parts
            if not NAME_RE.match(name):
                sys.exit(f"{path}:{lineno}: bad command name {name!r}")
            if name in seen:
                sys.exit(f"{path}:{lineno}: duplicate command {name!r}")
            seen.add(name)
            if kind not in KINDS:
                sys.exit(f"{path}:{lineno}: kind must be f, c or b")
            if windows and kind == "b":
                sys.exit(f"{path}:{lineno}: built-ins belong in commands.def only")
            if kind == "b" and name not in BUILTINS:
                sys.exit(f"{path}:{lineno}: {name!r} is not a known built-in")
            if kind == "f" and not (target.startswith("/") or (windows and WIN_PATH_RE.match(target))):
                sys.exit(f"{path}:{lineno}: file target must be an absolute path")
            if kind == "c":
                if not target or re.search(r"[;&|`$<>()'\"\\\\]", target):
                    sys.exit(f"{path}:{lineno}: command target must be plain argv")
            if not desc or len(desc) > 60:
                sys.exit(f"{path}:{lineno}: description must be 1-60 characters")
            entries.append((name, kind, target, desc))
    if not windows:
        builtin_names = {e[0] for e in entries if e[1] == "b"}
        missing = BUILTINS - builtin_names
        if missing:
            sys.exit(f"{path}: missing built-in entries: {sorted(missing)}")
    return entries


def windows_table(linux, win):
    """Built-ins come from the Linux list; Windows adds its own 'f' and 'c' entries."""
    names = {e[0] for e in win}
    clash = [e[0] for e in linux if e[0] in names]
    if clash:
        sys.exit(f"{DEF_WIN}: names clash with commands.def: {clash}")
    return [e for e in linux if e[1] == "b"] + win


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_rows(entries):
    return [f"    {{ {c_str(n)}, '{k}', {c_str(t)}, {c_str(d)} }}," for n, k, t, d in entries]


def render_c(linux, win):
    lines = [
        "/* GENERATED by tools/gen_commands.py from src/commands.def and",
        " * src/commands_windows.def. Do not edit. */",
        "#ifndef SUPER_RCT_COMMANDS_TABLE_H",
        "#define SUPER_RCT_COMMANDS_TABLE_H",
        "",
        "typedef struct {",
        "    const char *name;",
        "    char kind;          /* 'f' file, 'c' command, 'b' built-in */",
        "    const char *target; /* path or argv string */",
        "    const char *desc;",
        "} rct_cmd_def;",
        "",
        "#ifdef _WIN32",
        "static const rct_cmd_def RCT_COMMANDS[] = {",
    ]
    lines += c_rows(windows_table(linux, win))
    lines += ["};", "#else", "static const rct_cmd_def RCT_COMMANDS[] = {"]
    lines += c_rows(linux)
    lines += [
        "};",
        "#endif",
        "",
        "static const int RCT_NCOMMANDS = (int)(sizeof RCT_COMMANDS / sizeof RCT_COMMANDS[0]);",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def py_rows(entries):
    return [f"    ({n!r}, {k!r}, {t!r}, {d!r})," for n, k, t, d in entries]


def render_py(linux, win):
    lines = [
        "# GENERATED by tools/gen_commands.py from src/commands.def and",
        "# src/commands_windows.def. Do not edit.",
        "",
        "# (name, kind, target, description); kind: f = file, c = command, b = built-in",
        "import sys",
        "",
        "COMMANDS_LINUX = (",
    ]
    lines += py_rows(linux)
    lines += [")", "", "COMMANDS_WINDOWS = ("]
    lines += py_rows(windows_table(linux, win))
    lines += [")", "", "COMMANDS = COMMANDS_WINDOWS if sys.platform == \"win32\" else COMMANDS_LINUX", ""]
    return "\n".join(lines)


def main(argv):
    check = "--check" in argv
    linux = parse(DEF)
    win = parse(DEF_WIN, windows=True)
    outputs = {OUT_H: render_c(linux, win), OUT_PY: render_py(linux, win)}
    stale = []
    for path, text in outputs.items():
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
        if current != text:
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(text)
    if check:
        if stale:
            print("stale generated files:", *stale, sep="\n  ")
            return 1
        print(f"generated tables up to date ({len(linux)} Linux, {len(win)} Windows entries)")
        return 0
    print(f"wrote {len(linux)} Linux and {len(win)} Windows entries to {OUT_H} and {OUT_PY}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
